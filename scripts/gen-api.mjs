#!/usr/bin/env node
/**
 * Generates the REST contract types from the server's OpenAPI spec.
 *
 *   pnpm gen:api                       # reads ../server/build/openapi.json
 *   pnpm gen:api path/to/openapi.json  # or OPENAPI_SPEC=... pnpm gen:api
 *
 * The spec is written by the server test suite, without a running server:
 *   (cd ../server && ./gradlew test --tests '*OpenApiSpecExportTest')
 *
 * Output (committed — CI and other machines don't need the server checked out):
 *   src/shared/api/generated/schema.d.ts   paths / components / operations
 *   src/shared/api/generated/error-codes.ts  CoreExceptionCode → ERROR_CODES const
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const specPath = path.resolve(
  root,
  process.argv[2] ?? process.env.OPENAPI_SPEC ?? "../server/build/openapi.json",
);
const outDir = path.join(root, "src/shared/api/generated");

const BANNER = `/**
 * GENERATED by \`pnpm gen:api\` from the server's OpenAPI spec — do not edit by hand.
 * Regenerate after changing a server DTO, enum or CoreExceptionCode.
 */
`;

let spec;
try {
  spec = JSON.parse(await readFile(specPath, "utf8"));
} catch (error) {
  console.error(`Cannot read the OpenAPI spec at ${specPath}.`);
  console.error("Generate it with: (cd ../server && ./gradlew test --tests '*OpenApiSpecExportTest')");
  throw error;
}

const ast = await openapiTS(spec, { alphabetize: true });
const schema = BANNER + "\n" + astToString(ast);

const errorCodes = spec.components?.schemas?.ErrorCode?.["x-error-codes"];
if (!Array.isArray(errorCodes) || errorCodes.length === 0) {
  throw new Error("The spec has no components.schemas.ErrorCode x-error-codes (server OpenApiConfig).");
}
const entries = (pick) => errorCodes.map((c) => `  ${pick(c)},`).join("\n");
const errorCodesTs = `${BANNER}
/** Server CoreExceptionCode: name → the \`code\` of a failure response body. */
export const ERROR_CODES = {
${entries((c) => `${c.name}: ${c.code}`)}
} as const;

export type ErrorCodeName = keyof typeof ERROR_CODES;
export type ErrorCode = (typeof ERROR_CODES)[ErrorCodeName];

/** HTTP status the server answers with for each code. */
export const ERROR_CODE_STATUS: Record<ErrorCode, number> = {
${entries((c) => `${c.code}: ${c.status}`)}
};
`;

await mkdir(outDir, { recursive: true });
await writeFile(path.join(outDir, "schema.d.ts"), schema);
await writeFile(path.join(outDir, "error-codes.ts"), errorCodesTs);
console.log(`Generated ${path.relative(root, outDir)}/{schema.d.ts,error-codes.ts} from ${specPath}`);
